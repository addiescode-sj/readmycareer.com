"""
README results-table generator (render_results.py)
===================================================

Reads the latest eval CSVs and renders a Markdown "Quality & Evaluation" results
table, then injects it into README.md between the markers:

    <!-- EVAL:START -->
    ... generated table ...
    <!-- EVAL:END -->

If the markers are absent, the table is printed to stdout with a hint. This keeps
the published results table reproducible from the committed CSV artifacts rather
than hand-maintained.

Execution:
    cd eval && python render_results.py            # inject into README
    cd eval && python render_results.py --print    # print only
"""

from __future__ import annotations

import argparse
import csv
import math
from datetime import date
from pathlib import Path

EVAL_DIR = Path(__file__).parent
REPO_ROOT = EVAL_DIR.parent
README = REPO_ROOT / "README.md"
START = "<!-- EVAL:START -->"
END = "<!-- EVAL:END -->"


def _to_bool(v: str) -> bool | None:
    if v is None or v == "":
        return None
    return v.strip().lower() in ("true", "1", "yes")


def _to_float(v: str) -> float | None:
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else math.nan


def _rate(flags: list[bool | None]) -> float:
    present = [f for f in flags if f is not None]
    return (sum(1 for f in present if f) / len(present)) if present else math.nan


def _p95(values: list[float]) -> float:
    if not values:
        return math.nan
    s = sorted(values)
    idx = max(0, min(int(len(s) * 0.95), len(s) - 1))
    return s[idx]


def _pct(v: float) -> str:
    return "N/A" if math.isnan(v) else f"{v:.1%}"


def _num(v: float, fmt: str) -> str:
    return "N/A" if math.isnan(v) else format(v, fmt)


def read_rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def agent_metrics() -> list[tuple[str, str, str]]:
    """Returns (metric, value, threshold) rows from agent_harness_results.csv."""
    rows = read_rows(EVAL_DIR / "agent_harness_results.csv")
    if not rows:
        return []
    return [
        ("Schema Compliance", _pct(_rate([_to_bool(r.get("schema_valid")) for r in rows])), "≥ 95%"),
        ("Gap Recall (vs labels)", _pct(_mean([f for r in rows if (f := _to_float(r.get("gap_recall"))) is not None])), "≥ 50%"),
        ("Gap Faithfulness (LLM-judge)", _num(_mean([f for r in rows if (f := _to_float(r.get("gap_faithfulness"))) is not None]), ".3f"), "≥ 0.70"),
        ("Plan Completeness", _pct(_rate([_to_bool(r.get("plan_completeness")) for r in rows])), "≥ 90%"),
        ("Date Consistency", _pct(_rate([_to_bool(r.get("date_consistent")) for r in rows])), "= 100%"),
        ("p95 Latency", _num(_p95([f for r in rows if (f := _to_float(r.get("latency_s"))) is not None]), ".1f") + "s", "< 30s"),
        ("Avg Cost / Request", "$" + _num(_mean([f for r in rows if (f := _to_float(r.get("cost_usd"))) is not None]), ".4f"), "< $0.01"),
    ]


def rag_metrics() -> list[tuple[str, str, str]]:
    """Returns (metric, value, threshold) rows from ragas_results.csv + grounding_results.csv."""
    out: list[tuple[str, str, str]] = []
    rag = read_rows(EVAL_DIR / "ragas_results.csv")
    for col, label in (
        ("faithfulness", "RAG Faithfulness"),
        ("answer_relevancy", "Answer Relevancy"),
        ("context_precision", "Context Precision"),
        ("context_recall", "Context Recall"),
    ):
        vals = [f for r in rag if (f := _to_float(r.get(col))) is not None]
        if vals:
            out.append((label, _num(_mean(vals), ".3f"), "≥ 0.70"))

    grounding = read_rows(EVAL_DIR / "grounding_results.csv")
    targeted = [r for r in grounding if r.get("expected_doc_type")]
    if targeted:
        rate = _rate([_to_bool(r.get("grounded")) for r in targeted])
        out.append(("Grounding / Citation Rate", _pct(rate), "≥ 80%"))
    return out


def build_markdown() -> str:
    agent = agent_metrics()
    rag = rag_metrics()
    lines: list[str] = []
    lines.append(f"_Generated by `eval/render_results.py` on {date.today().isoformat()} from the committed eval CSVs._")
    lines.append("")

    if agent:
        lines.append("**Agent Output Quality**")
        lines.append("")
        lines.append("| Metric | Score | Threshold |")
        lines.append("| --- | --- | --- |")
        for metric, value, threshold in agent:
            lines.append(f"| {metric} | {value} | {threshold} |")
        lines.append("")

    if rag:
        lines.append("**RAG Retrieval Quality**")
        lines.append("")
        lines.append("| Metric | Score | Threshold |")
        lines.append("| --- | --- | --- |")
        for metric, value, threshold in rag:
            lines.append(f"| {metric} | {value} | {threshold} |")
        lines.append("")

    if not agent and not rag:
        lines.append("_No eval results found. Run `pnpm eval` to populate the CSVs._")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def inject(markdown: str) -> bool:
    if not README.exists():
        print("README.md not found.")
        return False
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"Markers {START} / {END} not found in README.md — printing table instead:\n")
        print(markdown)
        print(f"\nAdd the markers to README.md where the table should appear:\n{START}\n{END}")
        return False
    pre = text.split(START)[0]
    post = text.split(END, 1)[1]
    README.write_text(f"{pre}{START}\n{markdown}{END}{post}", encoding="utf-8")
    print(f"Injected results table into {README}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Render eval results table into README")
    parser.add_argument("--print", action="store_true", help="Print the table only (no README write)")
    args = parser.parse_args()

    markdown = build_markdown()
    if args.print:
        print(markdown)
        return 0
    inject(markdown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
